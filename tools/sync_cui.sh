#!/usr/bin/env bash
# Syncs the vendored CUI library (vendor/cui) with upstream.
#
#   tools/sync_cui.sh              sync to upstream master, pinned to its commit
#   tools/sync_cui.sh v1.4.0       sync to an explicit tag/branch/commit
#   tools/sync_cui.sh --check      report: vendored ref vs master HEAD vs latest release
#
# What it does: clones the ref shallowly into a temp dir, replaces exactly the
# vendored paths (include/ src/ third_party/ LICENSE), records ref + commit in
# vendor/cui/VENDOR.txt, regenerates the bindings (tools/gen.py) and runs the
# test suite. The build compiles vendor/cui/src by directory walk, so upstream
# adding or removing source files never breaks the build.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UPSTREAM="https://github.com/yappologistic/CUI.git"
VENDOR="$ROOT/vendor/cui"
PATHS=(include src third_party LICENSE)

current_ref() {
    awk '/^ref:/ {print $2}' "$VENDOR/VENDOR.txt" 2>/dev/null || echo "unknown"
}

current_commit() {
    awk '/^commit:/ {print $2}' "$VENDOR/VENDOR.txt" 2>/dev/null || echo "unknown"
}

latest_release() {
    if command -v gh >/dev/null 2>&1; then
        gh api repos/yappologistic/CUI/releases/latest --jq .tag_name 2>/dev/null && return
    fi
    git ls-remote --tags --sort=-v:refname "$UPSTREAM" 'v*' \
        | head -1 | sed 's|.*refs/tags/||; s|\^{}$||' | head -1
}

master_head() {
    git ls-remote "$UPSTREAM" refs/heads/master | awk '{print $1}'
}

if [[ "${1:-}" == "--check" ]]; then
    echo "vendored:        $(current_ref) @ $(current_commit)"
    echo "upstream master: $(master_head 2>/dev/null || echo unknown)"
    echo "latest release:  $(latest_release 2>/dev/null || echo unknown)"
    if [[ "$(current_commit)" == "$(master_head 2>/dev/null)" ]]; then
        echo "-> master: up to date"
    else
        echo "-> master has new commits: tools/sync_cui.sh"
    fi
    exit 0
fi

REF="${1:-master}"
echo "syncing CUI from $REF ..."
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if ! git clone -q --depth 1 --branch "$REF" "$UPSTREAM" "$TMP/cui" 2>/dev/null; then
    # arbitrary commit: fetch by SHA
    git init -q "$TMP/cui"
    git -C "$TMP/cui" remote add origin "$UPSTREAM"
    git -C "$TMP/cui" fetch -q --depth 1 origin "$REF"
    git -C "$TMP/cui" checkout -q FETCH_HEAD
fi
COMMIT="$(git -C "$TMP/cui" rev-parse HEAD)"
echo "upstream commit: $COMMIT"

cd "$ROOT"
for p in "${PATHS[@]}"; do
    rm -rf "$VENDOR/$p"
    cp -R "$TMP/cui/$p" "$VENDOR/$p"
done

# source manifest consumed by build.zig via @embedFile
(
    echo "# generated by tools/sync_cui.sh - list of C sources to compile"
    echo "# (excluding cui_bidi.c / cui_shape.c: optional text shaping)"
    cd "$TMP/cui"
    find src -name '*.c' ! -name 'cui_bidi.c' ! -name 'cui_shape.c' \
        ! -name 'cui_app_win32.c' ! -name 'cui_app_x11.c' ! -name 'cui_app_sdl2.c' ! -name 'cui_app_glfw.c' \
        ! -path 'src/platform/cui_app_cocoa*' | sort
) > "$VENDOR/SOURCES.txt"

cat > "$VENDOR/VENDOR.txt" <<EOF
ref: $REF
commit: $COMMIT
synced: $(date +%Y-%m-%d)
upstream: https://github.com/yappologistic/CUI
paths: ${PATHS[*]}
sync with: tools/sync_cui.sh [ref]
EOF

if git -C "$ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo
    echo "changes to vendored files:"
    git -C "$ROOT" add -A vendor/cui 2>/dev/null || true
    git -C "$ROOT" diff --cached --stat -- vendor/cui | tail -4
fi

echo
echo "regenerating bindings..."
python3 "$ROOT/tools/gen.py"

echo "running tests..."
if (cd "$ROOT" && zig build test) >/dev/null 2>&1; then
    echo "tests: PASS"
    echo
    echo "done - review and commit:"
    echo "  git add vendor/cui src/zui.zig && git commit -m 'sync CUI to $REF @ $COMMIT'"
else
    echo "tests: FAIL" >&2
    echo "the new CUI version needs attention - fix src/ or gen.py before committing" >&2
    exit 1
fi
